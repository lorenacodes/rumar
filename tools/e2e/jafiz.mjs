/** Viagem que já fiz (D-060/070): motivo "Evento", "Todos", lugar livre (bairro), depois apaga a viagem. */
import { chromium } from 'playwright';
const URL = process.env.URL ?? 'http://localhost:8793/';
const senha = process.env.E2E_SENHA ?? (() => { throw new Error('Defina E2E_SENHA'); })();
const b = await chromium.launch({ proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: 'localhost,127.0.0.1' } : undefined });
const erros = []; const confere = (r, ok) => { console.log(`   ${ok ? '✓' : '✗'} ${r}`); if (!ok) erros.push(r); };
const p = await (await b.newContext({ viewport: { width: 390, height: 1200 } })).newPage();
p.on('pageerror', (e) => erros.push(e.message));
p.on('dialog', (d) => d.accept());
await p.goto(URL); await p.locator('#nascimento').fill('15/03/1990'); await p.getByRole('button', { name: /Continuar/ }).click(); await p.waitForTimeout(1500);
await p.goto(URL + '#/entrar'); await p.locator('#email').fill('e2e.tempo@bovair.com.br'); await p.locator('#senha').fill(senha); await p.getByRole('button', { name: /^Entrar/ }).click(); await p.waitForTimeout(4000);
await p.goto(URL + '#/viagens/ja-fiz'); await p.waitForTimeout(2000);
await p.locator('#busca-destino-geral').fill('Recife'); await p.waitForTimeout(2500);
await p.locator('ul[aria-label="Cidades encontradas"] button').first().click(); await p.waitForTimeout(500);
await p.getByRole('radio', { name: 'Evento' }).click();
await p.getByLabel('Qual evento?').fill("REC'n'Play");
await p.getByRole('radio', { name: 'Todos' }).click();
confere('explica o "Todos"', await p.getByText('Quem tem conta vê o roteiro e as fotos').isVisible());
await p.getByRole('button', { name: 'Salvar viagem' }).click(); await p.waitForTimeout(5000);
confere('abre a viagem', /#\/viagem\//.test(p.url()));
confere('mostra o evento', await p.getByText("Evento: REC'n'Play").isVisible().catch(() => false));
await p.getByPlaceholder(/Ex.: um restaurante de/).fill('Bairro do Recife Teste');
await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Registrar "Bairro do Recife Teste"/ }).click(); await p.waitForTimeout(3000);
confere('lugar livre registrado', await p.getByText('Bairro do Recife Teste').first().isVisible().catch(() => false));
await p.getByRole('button', { name: 'Apagar viagem' }).click(); await p.waitForTimeout(4000);
confere('viagem apagada', /#\/viagens$/.test(p.url()));
console.log(erros.length ? `ERROS: ${erros.join(' | ')}` : 'Tudo certo.');
await b.close(); process.exit(erros.length ? 1 : 0);
