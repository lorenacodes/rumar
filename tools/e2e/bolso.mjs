/** Bolso da viagem (D-077): custo por partes, previsão com gráfico, "Guardei dinheiro" na viagem. Apaga no fim. */
import { chromium } from 'playwright';
const URL = process.env.URL ?? 'http://localhost:8793/';
const senha = process.env.E2E_SENHA ?? (() => { throw new Error('Defina E2E_SENHA'); })();
const OUT = process.env.OUT;
const b = await chromium.launch({ proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: 'localhost,127.0.0.1' } : undefined });
const erros = []; const confere = (r, ok) => { console.log(`   ${ok ? '✓' : '✗'} ${r}`); if (!ok) erros.push(r); };
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, permissions: ['clipboard-read', 'clipboard-write'] });
const p = await ctx.newPage();
p.on('pageerror', (e) => erros.push(e.message)); p.on('dialog', (d) => d.accept());
await p.goto(URL + '#/idade'); await p.locator('#nascimento').fill('15/03/1990'); await p.getByRole('button', { name: /Continuar/ }).click(); await p.waitForTimeout(1500);
await p.goto(URL + '#/entrar'); await p.locator('#email').fill('e2e.tempo@bovair.com.br'); await p.locator('#senha').fill(senha); await p.getByRole('button', { name: /^Entrar/ }).click(); await p.waitForTimeout(4000);
await p.goto(URL + '#/viagens'); await p.waitForTimeout(2500);
confere('"Registrar viagem que já fiz" é um botão de verdade', (await p.getByRole('button', { name: 'Registrar viagem que já fiz' }).evaluate((e) => e.offsetHeight)) >= 48);
await p.goto(URL + '#/viagens/nova?d=br-2611606'); await p.waitForTimeout(3000);
await p.getByLabel(/Passagem ida e volta/).fill('800');
await p.getByLabel(/Hospedagem por noite/).fill('300');
await p.getByLabel(/Comida, passeios/).fill('150');
const tranquilo = await p.getByText('Para viajar com tranquilidade').locator('..').innerText();
confere('soma com 10% de reserva (3.520)', /3\.520/.test(tranquilo));
await p.getByLabel(/Já guardei/).fill('500');
await p.getByLabel(/Consigo guardar por mês/).fill('400');
await p.waitForTimeout(500);
confere('previsão diz quando junta', await p.getByText(/Você junta tudo em|Na data, faltariam/).first().isVisible());
confere('gráfico aparece', (await p.locator('figure svg[role=img]').count()) === 1);
if (OUT) await p.screenshot({ path: `${OUT}/nova-bolso.png`, fullPage: true });
await p.getByRole('button', { name: 'Criar viagem' }).click(); await p.waitForTimeout(8000);
confere('abre a viagem', /#\/viagem\//.test(p.url()));
const bolso = p.getByRole('region', { name: 'Dinheiro da viagem' });
confere('topo da viagem mostra o bolso com gráfico', (await bolso.locator('svg[role=img]').count()) === 1);
if (OUT) await p.screenshot({ path: `${OUT}/viagem-bolso.png` });
await bolso.getByRole('button', { name: 'Guardei dinheiro' }).click();
await bolso.getByLabel(/Quanto guardou/).fill('200');
await bolso.getByRole('button', { name: 'Salvar' }).click(); await p.waitForTimeout(4000);
confere('registra o que guardou', /700/.test(await bolso.innerText()));
// D-087: compartilhar o roteiro (no navegador de teste, copia o texto).
await p.getByRole('tab', { name: 'Roteiro' }).click().catch(() => p.getByText('Roteiro', { exact: true }).first().click()); await p.waitForTimeout(2500);
await p.evaluate(() => { Object.defineProperty(navigator, 'share', { value: undefined, configurable: true }); });
await p.getByRole('button', { name: 'Compartilhar' }).first().click(); await p.waitForTimeout(1000);
const copiado = await p.evaluate(() => navigator.clipboard.readText()).catch(() => '');
confere('compartilhar copia o roteiro com os dias', /Roteiro: Recife/.test(copiado) && /Dia 1/.test(copiado) && !/R\$/.test(copiado));
await p.getByText(/^Grupo/).first().click(); await p.waitForTimeout(1500);
await p.getByRole('button', { name: 'Apagar viagem' }).click(); await p.waitForTimeout(4000);
confere('viagem de teste apagada', /#\/viagens$/.test(p.url()));
console.log(erros.length ? `ERROS: ${erros.join(' | ')}` : 'Tudo certo.');
await b.close(); process.exit(erros.length ? 1 : 0);
